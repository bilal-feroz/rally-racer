// Capture UI states from the normal (non-test) boot: title, countdown, pause.
import { chromium } from '@playwright/test';
import fs from 'node:fs';
const out = process.argv[2] ?? 'screenshots';
const BASE = process.env.RALLY_URL ?? 'http://127.0.0.1:5173/';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
const t0 = Date.now();
await page.goto(BASE + '?audio=0');
await page.getByRole('button', { name: 'Start stage' }).waitFor({ timeout: 90000 });
console.log(`title ready after ${((Date.now() - t0) / 1000).toFixed(1)} s`);
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/ui-title.png` });
await page.getByRole('button', { name: 'Start stage' }).click();
await page.waitForTimeout(1400);
await page.screenshot({ path: `${out}/ui-countdown.png` });
await page.waitForTimeout(2600);
await page.keyboard.down('KeyW');
await page.waitForTimeout(2500);
await page.keyboard.up('KeyW');
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/ui-pause.png` });
console.log('errors', JSON.stringify(errors));
await browser.close();
